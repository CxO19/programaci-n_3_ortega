const valorInmueble = 150000;
const mesesPlazo = 12;

// Operaciones básicas
console.log(valorInmueble + 5000);   // 155000 — suma (precio con extras)
console.log(valorInmueble - 10000);  // 140000 — resta (descuento aplicado)
console.log(valorInmueble * 0.12);   // 18000  — multiplicación (cálculo de IVA)
console.log(valorInmueble / mesesPlazo); // 12500 — división (cuota mensual sin interés)
console.log(valorInmueble % 1000);   // 0      — módulo (residuo de división por lote)
console.log(10 ** 2);                // 100    — potencia (superficie cuadrada base)